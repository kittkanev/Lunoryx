"""Embed a DejaVu Sans TTF (fonttools pyftsubset can reduce it first)."""
import sys
from pathlib import Path
font = Path(sys.argv[1]).read_bytes()
Path('assets/font_data.h').write_text('// DejaVu Sans subset; see docs/licenses/DejaVu.txt. Generated by tools/embed_font.py\n#pragma once\nstatic const unsigned char kStudioFont[] = {\n'+','.join(str(x) for x in font)+'\n};\n')
